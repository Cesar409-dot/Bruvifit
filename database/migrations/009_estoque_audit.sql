-- SOMENTE LEITURA. Usar na instância configurada antes de aprovar a migração.
SELECT DATABASE() AS banco, VERSION() AS versao;
SHOW CREATE TABLE produto;
SHOW CREATE TABLE estoque;
SHOW CREATE TABLE pedido;
SHOW CREATE TABLE item_pedido;
SELECT TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME IN ('produto', 'estoque', 'pedido', 'item_pedido')
ORDER BY TABLE_NAME, ORDINAL_POSITION;
SELECT TABLE_NAME, INDEX_NAME, NON_UNIQUE, COLUMN_NAME, SEQ_IN_INDEX
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME IN ('produto', 'estoque', 'pedido', 'item_pedido')
ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX;
